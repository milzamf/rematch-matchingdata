type TranslationKey = keyof typeof translations.en;
type TranslationValues = Record<string, string | number>;

const PreferencesContext = createContext<PreferencesContextValue | null>(null);

function getSystemTheme() {
  if (typeof window === "undefined") return "light";
  return window.matchMedia("(prefers-color-scheme: dark)").matches ? "dark" : "light";
}

function readPreferences(): Preferences {
  if (typeof window === "undefined") return defaultPreferences;
  try {
    const raw = window.localStorage.getItem(PREFERENCES_KEY);
    if (!raw) return defaultPreferences;
    const parsed = JSON.parse(raw) as Partial<Preferences>;
    return {
      theme:
        parsed.theme === "light" || parsed.theme === "dark" || parsed.theme === "system"
          ? parsed.theme
          : defaultPreferences.theme,
      language:
        parsed.language === "en" || parsed.language === "id"
          ? parsed.language
          : defaultPreferences.language,
    };
  } catch {
    return defaultPreferences;
  }
}

function writePreferences(preferences: Preferences) {
  if (typeof window === "undefined") return;
  window.localStorage.setItem(PREFERENCES_KEY, JSON.stringify(preferences));
}

export function PreferencesProvider({ children }: { children: ReactNode }) {
  const [preferences, setPreferences] = useState<Preferences>(defaultPreferences);
  const [hydrated, setHydrated] = useState(false);
  const [systemTheme, setSystemTheme] = useState<"light" | "dark">("light");

  useEffect(() => {
    setPreferences(readPreferences());
    setSystemTheme(getSystemTheme());
    setHydrated(true);
  }, []);

  useEffect(() => {
    if (typeof window === "undefined") return;
    const query = window.matchMedia("(prefers-color-scheme: dark)");
    const onChange = (event: MediaQueryListEvent) => {
      setSystemTheme(event.matches ? "dark" : "light");
    };
    query.addEventListener("change", onChange);
    return () => query.removeEventListener("change", onChange);
  }, []);

  const resolvedTheme = preferences.theme === "system" ? systemTheme : preferences.theme;

  useEffect(() => {
    if (typeof document === "undefined") return;
    document.documentElement.classList.toggle("dark", resolvedTheme === "dark");
    document.documentElement.lang = preferences.language;
  }, [preferences.language, resolvedTheme]);

  useEffect(() => {
    if (hydrated) writePreferences(preferences);
  }, [hydrated, preferences]);

  const value = useMemo<PreferencesContextValue>(
    () => ({
      ...preferences,
      hydrated,
      resolvedTheme,
      setTheme: (theme) => setPreferences((current) => ({ ...current, theme })),
      setLanguage: (language) => setPreferences((current) => ({ ...current, language })),
      t: (key, values) =>
        interpolate(translations[preferences.language][key] ?? translations.en[key], values),
    }),
    [hydrated, preferences, resolvedTheme],
  );

  return <PreferencesContext.Provider value={value}>{children}</PreferencesContext.Provider>;
}

export function usePreferences() {
  const ctx = useContext(PreferencesContext);
  if (!ctx) throw new Error("usePreferences must be used inside PreferencesProvider");
  return ctx;
}

function interpolate(template: string, values?: TranslationValues) {
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (match, key) =>
    values[key] === undefined ? match : String(values[key]),
  );
}
